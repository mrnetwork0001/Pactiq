// Regenerates src/lib/pactiqAbi.ts from the Foundry build output.
// Usage: (cd ../contracts && forge build) && node scripts/export-abi.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
for (const [contract, constName, file] of [
  ["PactiqVault", "PACTIQ_ABI", "pactiqAbi.ts"],
  ["PactiqBadges", "BADGES_ABI", "badgesAbi.ts"],
]) {
  const artifact = resolve(here, `../../contracts/out/${contract}.sol/${contract}.json`);
  const out = resolve(here, `../src/lib/${file}`);
  const { abi } = JSON.parse(readFileSync(artifact, "utf8"));
  writeFileSync(
    out,
    `// AUTO-GENERATED by scripts/export-abi.mjs from contracts/out. Do not edit by hand.\nexport const ${constName} = ${JSON.stringify(abi, null, 2)} as const;\n`
  );
  console.log(`Wrote ${abi.length} ${contract} ABI entries to ${out}`);
}
